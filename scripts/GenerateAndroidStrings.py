#!/usr/bin/env python3
"""Generate Android resources from the shared Apple catalog and Android-only copy."""
import argparse
import hashlib
import json
from pathlib import Path
import re
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ("en", "it", "fr", "de", "es")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = json.loads((ROOT / "Resources/Localizable.xcstrings").read_text())
    messages = {}
    for entry in catalog["strings"].values():
        translations = {lang: entry.get("localizations", {}).get(lang, {}).get("stringUnit", {}).get("value") for lang in LOCALES}
        if translations["en"] and all(translations.values()):
            messages[translations["en"]] = translations
    messages.update(json.loads((ROOT / "android/strings.json").read_text()))
    messages["Makeet"] = {lang: "Makeet" for lang in LOCALES}
    source = "\n".join(p.read_text() for p in (ROOT / "android/app/src/main/java").rglob("*.kt") if p.name != "Strings.kt")
    literals = {json.loads(value) for value in re.findall(r'"(?:\\.|[^"\\\n])*"', source)}
    direct = set(re.findall(r'\bt\("([^"\n]+)"\)', source)) | set(re.findall(r'\bl\(context, "([^"\n]+)"\)', source))
    missing = direct - messages.keys()
    if missing:
        raise SystemExit("Missing translations: " + str(sorted(missing)))
    used = ((literals | direct) & messages.keys()) | {"Makeet"}
    keys = {key: "app_name" if key == "Makeet" else "s_" + hashlib.sha256(key.encode()).hexdigest()[:12] for key in sorted(used)}
    files = {}
    for lang in LOCALES:
        lines = ['<resources>']
        for key, name in keys.items():
            value = messages[key][lang]
            if not value:
                raise SystemExit(f"Missing {lang}: {key}")
            value = escape(value.replace("\\", "\\\\").replace("\n", "\\n").replace("'", "\\'").replace('"', '\\"'))
            lines.append(f'    <string name="{name}" formatted="false">{value}</string>')
        lines.append('</resources>')
        folder = "values" if lang == "en" else f"values-{lang}"
        files[ROOT / f"android/app/src/main/res/{folder}/strings.xml"] = "\n".join(lines) + "\n"
    entries = [f"        {json.dumps(key, ensure_ascii=False)} to R.string.{name}," for key, name in keys.items()]
    files[ROOT / "android/app/src/main/java/org/turinglabs/makeet/Strings.kt"] = "package org.turinglabs.makeet\n\n// Generated by scripts/GenerateAndroidStrings.py.\nobject Strings {\n    val resources = mapOf(\n" + "\n".join(entries) + "\n    )\n}\n"
    for path, value in files.items():
        if args.check:
            if not path.exists() or path.read_text() != value:
                raise SystemExit("Outdated Android resource: " + str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(value)
    print(f"Verified {len(keys)} Android messages in {len(LOCALES)} languages")


if __name__ == "__main__":
    main()
